"""Threshold sweep on DEV seeds, then a single HELD-OUT evaluation. Selection rule fixed in advance:

  among span configs with dev laundering <= 0.01 (pooled over regimes and families), pick the lowest dev
  creep; ties -> larger tau_taint. Held-out seed >= 1000 is touched once, after selection.

python -m evals.sweep --out docs/RESULTS_TOY.md
"""
from __future__ import annotations

import argparse
import itertools
import time
from collections import Counter

from taintmem import Attributor, SpanPropagator

from .laundering import evaluate, generate, make_propagators, summarize

REGIMES = [("easy", 0.0, False), ("drift0.6+mix", 0.6, True), ("drift0.9+mix", 0.9, True)]


def pooled(scs, prop, k):
    tot = Counter()
    for _, drift, mix in REGIMES:
        tot.update(evaluate(scs, {"p": prop}, k, drift, mix)["p"])
    return tot


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev-n", type=int, default=40)
    ap.add_argument("--test-n", type=int, default=160)
    ap.add_argument("--passes", type=int, default=3)
    ap.add_argument("--out", default="docs/RESULTS_TOY.md")
    a = ap.parse_args()
    dev = generate(a.dev_n, seed=0)
    attrs = {"plain": Attributor(), "idf": Attributor(idf=True)}
    rows = []
    t0 = time.time()
    for an, dom, tt, tc in itertools.product(attrs, (False, True), (0.15, 0.25, 0.35, 0.5), (0.4, 0.6, 0.8)):
        if tc < tt:
            continue
        m = summarize(pooled(dev, SpanPropagator(attrs[an], tt, tc, dom), a.passes))
        rows.append((an, dom, tt, tc, m))
    ok = [r for r in rows if r[4]["laundering"] <= 0.01]
    best = min(ok, key=lambda r: (r[4]["creep"], -r[2])) if ok else None
    lines = ["# Toy-benchmark results (GENERATED by `python -m evals.sweep`)", "",
             "**Machinery test only.** Scenarios and the summariser are rule-based and written by the authors;",
             "nothing here is evidence about real LLMs. Dev seeds < 1000, held-out seed 1000.", "",
             f"## Dev sweep ({len(rows)} configs, {time.time() - t0:.0f}s, pooled over regimes {[r[0] for r in REGIMES]}, k={a.passes})", "",
             "| attributor | anchor_dominates | tau_taint | tau_clear | creep | usable | laundering |", "|---|---|---|---|---|---|---|"]
    for an, dom, tt, tc, m in sorted(rows, key=lambda r: (r[4]["laundering"], r[4]["creep"])):
        lines.append(f"| {an} | {dom} | {tt} | {tc} | {m['creep']:.3f} | {m['usable']:.3f} | {m['laundering']:.3f} |")
    lines += ["", f"Selected on dev: `{best[:4] if best else None}`" if best else "No config met laundering <= 0.01 on dev.", ""]
    test = generate(a.test_n, seed=1000)
    for name, drift, mix in REGIMES:
        props = make_propagators()
        if best:
            an, dom, tt, tc, _ = best
            props["span_selected"] = SpanPropagator(attrs[an], tt, tc, dom)
        res = evaluate(test, props, a.passes, drift, mix)
        lines += [f"## Held-out (seed 1000, n={a.test_n}), regime `{name}`, k={a.passes}", "",
                  "| propagator | creep | usable trusted | laundering | synthesis kept |", "|---|---|---|---|---|"]
        for k, c in res.items():
            m = summarize(c)
            lines.append(f"| {k} | {m['creep']:.3f} | {m['usable']:.3f} | {m['laundering']:.3f} | {m['synthesis']:.2f} |")
        lines.append("")
    res = evaluate(test, {k: v for k, v in make_propagators().items() if k.startswith("span")}, a.passes, 0.6, True, by_family=True)
    lines += ["## Held-out per family (drift0.6+mix), laundering only", "", "| propagator | family | laundering |", "|---|---|---|"]
    for (n, f), c in res.items():
        if summarize(c)["laundering"] > 0:
            lines.append(f"| {n} | {f} | {summarize(c)['laundering']:.3f} |")
    lines.append("")
    open(a.out, "w").write("\n".join(lines))
    print("\n".join(lines[-60:]))


if __name__ == "__main__":
    main()
